int CvLuaTeam::pRegister(lua_State* L)
{
	lua_getglobal(L, "Teams");
	if(lua_isnil(L, -1))
	{
		lua_pop(L, 1);
		lua_newtable(L);
		lua_pushvalue(L, -1);
		lua_setglobal(L, "Teams");
	}

	for(int i = 0; i < REALLY_MAX_TEAMS; ++i)
	{
		CvTeam* pkTeam = &CvTeam::getTeam((TeamTypes)i);
		CvLuaTeam::Push(L, pkTeam);
		lua_rawseti(L, -2, i);
	}

	return 0;
}


